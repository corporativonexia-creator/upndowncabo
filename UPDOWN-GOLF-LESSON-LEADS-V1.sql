begin;

create table if not exists public.golf_lesson_leads (
  id uuid primary key default gen_random_uuid(),
  public_token uuid not null default gen_random_uuid(),

  name text not null,
  phone text not null,
  phone_digits text not null,

  skill_level text not null
    check (skill_level in ('new','beginner','intermediate','advanced','competitive')),

  goal_category text not null
    check (goal_category in ('starting','consistency','distance','irons','short_game','putting','strategy','other')),

  goal_text text,

  consent_contact boolean not null default true
    check (consent_contact = true),
  consent_at timestamptz not null default now(),
  consent_version text not null default 'golf_lessons_contact_v1',
  consent_text text not null,

  language text not null default 'es'
    check (language in ('es','en')),

  source text not null default 'home_classes',
  affiliate_code text,

  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  utm_term text,
  referrer_host text,

  selected_instructor text
    check (selected_instructor is null or selected_instructor in ('rodrigo-uribe','mario-navarro')),
  selected_at timestamptz,

  status text not null default 'new'
    check (status in ('new','contacted','qualified','scheduled','completed','closed')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists golf_lesson_leads_public_token_key
  on public.golf_lesson_leads(public_token);

create index if not exists golf_lesson_leads_created_at_idx
  on public.golf_lesson_leads(created_at desc);

create index if not exists golf_lesson_leads_skill_level_idx
  on public.golf_lesson_leads(skill_level);

create index if not exists golf_lesson_leads_goal_category_idx
  on public.golf_lesson_leads(goal_category);

create index if not exists golf_lesson_leads_selected_instructor_idx
  on public.golf_lesson_leads(selected_instructor);

create index if not exists golf_lesson_leads_affiliate_code_idx
  on public.golf_lesson_leads(affiliate_code);

create index if not exists golf_lesson_leads_phone_digits_idx
  on public.golf_lesson_leads(phone_digits);


create table if not exists public.golf_lesson_events (
  id bigint generated by default as identity primary key,
  lead_id uuid not null references public.golf_lesson_leads(id) on delete cascade,
  event_type text not null
    check (event_type in ('lead_created','instructor_interest')),
  instructor_slug text
    check (instructor_slug is null or instructor_slug in ('rodrigo-uribe','mario-navarro')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists golf_lesson_events_lead_id_idx
  on public.golf_lesson_events(lead_id);

create index if not exists golf_lesson_events_created_at_idx
  on public.golf_lesson_events(created_at desc);

create index if not exists golf_lesson_events_instructor_idx
  on public.golf_lesson_events(instructor_slug);


