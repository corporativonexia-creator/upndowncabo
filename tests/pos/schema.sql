CREATE OR REPLACE FUNCTION public.pos_void_sale(p_device_token text, p_sale_id uuid, p_reason text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_employee public.pos_employees%rowtype;
  v_terminal public.pos_terminals%rowtype;
  v_shift public.pos_shifts%rowtype;
  v_sale public.pos_sales%rowtype;
  v_item record;
  v_product public.products%rowtype;
  v_reason text;
begin
  v_reason := btrim(coalesce(p_reason,''));

  if length(v_reason) < 4 then
    raise exception 'VOID_REASON_REQUIRED';
  end if;

  select e.*
  into v_employee
  from public.pos_employees e
  where e.auth_user_id = auth.uid();

  if not found or v_employee.status <> 'active' then
    raise exception 'POS_EMPLOYEE_NOT_ACTIVE';
  end if;

  if v_employee.role not in ('supervisor','pos_admin') then
    raise exception 'SUPERVISOR_REQUIRED';
  end if;

  select t.*
  into v_terminal
  from public.pos_terminals t
  where t.status = 'active'
    and t.device_token_hash =
      extensions.digest(
        convert_to(coalesce(p_device_token,''),'UTF8'),
        'sha256'
      );

  if not found then
    raise exception 'TERMINAL_NOT_AUTHORIZED';
  end if;

  select s.*
  into v_shift
  from public.pos_shifts s
  where s.employee_id = v_employee.id
    and s.terminal_id = v_terminal.id
    and s.status = 'open'
  order by s.opened_at desc
  limit 1
  for update;

  if not found then
    raise exception 'NO_OPEN_SHIFT';
  end if;

  select ps.*
  into v_sale
  from public.pos_sales ps
  where ps.id = p_sale_id
  for update;

  if not found then
    raise exception 'SALE_NOT_FOUND';
  end if;

  if v_sale.status <> 'completed' then
    raise exception 'SALE_NOT_REVERSIBLE:%', v_sale.status;
  end if;

  if v_sale.shift_id <> v_shift.id then
    raise exception 'VOID_ONLY_CURRENT_SHIFT';
  end if;

  for v_item in
    select psi.product_id, psi.quantity, psi.sku
    from public.pos_sale_items psi
    where psi.sale_id = v_sale.id
  loop
    select p.*
    into v_product
    from public.products p
    where p.id = v_item.product_id
    for update;

    if not found then
      raise exception 'PRODUCT_NOT_FOUND:%', v_item.product_id;
    end if;

    insert into public.inventory_movements(
      product_id,
      order_id,
      pos_sale_id,
      movement_type,
      quantity_change,
      stock_before,
      stock_after,
      note
    )
    values(
      v_product.id,
      null,
      v_sale.id,
      'sale',
      v_item.quantity,
      v_product.stock,
      v_product.stock + v_item.quantity,
      format(
        'ANULACIÓN POS #%s · reposición de inventario · %s',
        v_sale.sale_number,
        v_reason
      )
    );

    update public.products p
    set
      stock = p.stock + v_item.quantity,
      updated_at = now()
    where p.id = v_product.id;

    insert into public.pos_sale_events(
      sale_id,
      employee_id,
      terminal_id,
      event_type,
      details
    )
    values(
      v_sale.id,
      v_employee.id,
      v_terminal.id,
      'inventory_restored',
      jsonb_build_object(
        'operation', 'void',
        'product_id', v_product.id,
        'sku', v_item.sku,
        'quantity', v_item.quantity,
        'stock_before', v_product.stock,
        'stock_after', v_product.stock + v_item.quantity
      )
    );
  end loop;

  update public.pos_sales ps
  set
    status = 'voided',
    voided_at = now(),
    voided_by = v_employee.id,
    void_reason = v_reason,
    updated_at = now()
  where ps.id = v_sale.id;

  insert into public.pos_sale_events(
    sale_id,
    employee_id,
    terminal_id,
    event_type,
    details
  )
  values(
    v_sale.id,
    v_employee.id,
    v_terminal.id,
    'sale_voided',
    jsonb_build_object(
      'sale_number', v_sale.sale_number,
      'amount', v_sale.total,
      'reason', v_reason
    )
  );

  return jsonb_build_object(
    'ok', true,
    'operation', 'void',
    'sale_id', v_sale.id,
    'sale_number', v_sale.sale_number,
    'amount', v_sale.total,
    'status', 'voided'
  );
end;
$function$
