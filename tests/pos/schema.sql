        convert_to(coalesce(p_device_token,''),'UTF8'),
        'sha256'
      );

  if not found then
    raise exception 'TERMINAL_NOT_AUTHORIZED';
  end if;

  select s.*
  into v_shift
  from public.pos_shifts s
  where s.employee_id = v_employee.id
    and s.terminal_id = v_terminal.id
    and s.status = 'open'
  order by s.opened_at desc
  limit 1;

  if not found then
    raise exception 'NO_OPEN_SHIFT';
  end if;

  v_query := nullif(btrim(coalesce(p_query,'')),'');

  if v_query is null and p_date_from is null and p_date_to is null then
    raise exception 'SEARCH_CRITERIA_REQUIRED';
  end if;

  if p_date_from is not null then
    v_from := (p_date_from::timestamp at time zone 'America/Mazatlan');
  end if;

  if p_date_to is not null then
    v_to := ((p_date_to + 1)::timestamp at time zone 'America/Mazatlan');
  end if;

  with matched as (
    select distinct ps.id
    from public.pos_sales ps
    left join public.pos_sale_items psi on psi.sale_id = ps.id
    left join public.pos_payments pp on pp.sale_id = ps.id
    where ps.status = 'completed'
      and not exists (
        select 1
        from public.pos_refunds pr
        where pr.sale_id = ps.id
      )
      and (v_from is null or ps.created_at >= v_from)
      and (v_to is null or ps.created_at < v_to)
      and (
        v_query is null
        or ps.sale_number::text ilike '%' || v_query || '%'
        or coalesce(psi.product_name,'') ilike '%' || v_query || '%'
        or coalesce(psi.sku,'') ilike '%' || v_query || '%'
        or coalesce(pp.reference,'') ilike '%' || v_query || '%'
      )
  ),
  rows as (
    select
      ps.id,
      ps.sale_number,
      ps.status,
      ps.currency,
      ps.total,
      ps.created_at,
      pe.employee_number,
      pe.full_name as employee_name,
      pt.name as terminal_name,

      coalesce((
        select string_agg(distinct nullif(btrim(psi.product_name),''), ', ')
        from public.pos_sale_items psi
        where psi.sale_id = ps.id
      ), '') as products,

      coalesce((
        select string_agg(distinct nullif(btrim(psi.sku),''), ', ')
        from public.pos_sale_items psi
        where psi.sale_id = ps.id
      ), '') as skus,

      coalesce((
        select string_agg(distinct pp.method, ', ')
        from public.pos_payments pp
        where pp.sale_id = ps.id
      ), '') as payment_methods,

      coalesce((
        select string_agg(distinct nullif(btrim(pp.reference),''), ', ')
        from public.pos_payments pp
        where pp.sale_id = ps.id
      ), '') as payment_references

    from matched m
    join public.pos_sales ps on ps.id = m.id
    left join public.pos_employees pe on pe.id = ps.employee_id
    left join public.pos_terminals pt on pt.id = ps.terminal_id
    order by ps.created_at desc
    limit greatest(1,least(coalesce(p_limit,50),100))
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', r.id,
        'sale_number', r.sale_number,
        'status', r.status,
        'currency', r.currency,
        'total', r.total,
        'created_at', r.created_at,
        'employee_number', r.employee_number,
        'employee_name', r.employee_name,
        'terminal_name', r.terminal_name,
        'products', r.products,
        'skus', r.skus,
        'payment_methods', r.payment_methods,
        'payment_references', r.payment_references
      )
      order by r.created_at desc
    ),
    '[]'::jsonb
  )
  into v_rows
  from rows r;

  return jsonb_build_object(
    'ok', true,
    'count', jsonb_array_length(v_rows),
    'sales', v_rows,
    'timezone', 'America/Mazatlan'
  );
end;
