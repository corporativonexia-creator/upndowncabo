CREATE OR REPLACE FUNCTION public.sync_product_stock_from_variants()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_product_id uuid;
  v_default_id uuid;
  v_total integer;
begin
  v_product_id := coalesce(new.product_id, old.product_id);

  -- Guarantee one default variant per product. Prefer the existing default;
  -- otherwise promote the oldest active variant.
  select id into v_default_id
  from public.product_variants
  where product_id = v_product_id and is_default = true
  order by created_at asc
  limit 1;

  if v_default_id is null then
    select id into v_default_id
    from public.product_variants
    where product_id = v_product_id and is_active = true
    order by created_at asc
    limit 1;

    if v_default_id is not null then
      update public.product_variants
      set is_default = (id = v_default_id), updated_at = now()
      where product_id = v_product_id;
    end if;
  end if;

  -- Storefront stock is the sum of active variants, so multi-size/color
  -- products remain correct as well as single-variant products.
  select coalesce(sum(stock),0)::integer into v_total
  from public.product_variants
  where product_id = v_product_id and is_active = true;

  update public.products
  set stock = v_total, updated_at = now()
  where id = v_product_id and stock is distinct from v_total;

  return coalesce(new, old);
end;
$function$
;
CREATE TRIGGER trg_sync_product_stock_from_variants AFTER INSERT OR DELETE OR UPDATE OF stock, is_active, is_default ON public.product_variants FOR EACH ROW EXECUTE FUNCTION sync_product_stock_from_variants();
CREATE OR REPLACE FUNCTION public.sync_single_variant_to_product()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_product_id uuid;
  v_count integer;
  v_variant public.product_variants%rowtype;
begin
  v_product_id := coalesce(new.product_id, old.product_id);

  select count(*) into v_count
  from public.product_variants
  where product_id=v_product_id and is_active=true;

  if v_count=1 then
    select * into v_variant
    from public.product_variants
    where product_id=v_product_id and is_active=true
    limit 1;

    update public.products
    set barcode=coalesce(nullif(btrim(v_variant.barcode),''),barcode),
        stock=coalesce(v_variant.stock,stock),
        updated_at=now()
    where id=v_product_id;
  end if;

  return coalesce(new,old);
end;
$function$
;
CREATE TRIGGER trg_sync_single_variant_to_product AFTER INSERT OR DELETE OR UPDATE ON public.product_variants FOR EACH ROW EXECUTE FUNCTION sync_single_variant_to_product();
CREATE OR REPLACE FUNCTION public.pos_close_shift(p_device_token text, p_closing_cash numeric, p_notes text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_employee public.pos_employees%rowtype;
  v_terminal public.pos_terminals%rowtype;
  v_shift public.pos_shifts%rowtype;
  v_cash_sales numeric(12,2) := 0;
  v_cash_refunds numeric(12,2) := 0;
  v_cash_in numeric(12,2) := 0;
  v_cash_out numeric(12,2) := 0;
  v_expected numeric(12,2) := 0;
  v_difference numeric(12,2) := 0;
begin
  select e.*
  into v_employee
  from public.pos_employees e
  where e.auth_user_id = auth.uid();

  if not found or v_employee.status <> 'active' then
    raise exception 'EMPLOYEE_NOT_ACTIVE';
  end if;

  select t.*
  into v_terminal
  from public.pos_terminals t
  where t.status = 'active'
    and t.device_token_hash =
      extensions.digest(convert_to(coalesce(p_device_token,''),'UTF8'),'sha256');

  if not found then
    raise exception 'TERMINAL_NOT_AUTHORIZED';
  end if;

  select s.*
  into v_shift
  from public.pos_shifts s
  where s.employee_id = v_employee.id
    and s.terminal_id = v_terminal.id
    and s.status = 'open'
  order by s.opened_at desc
  limit 1
  for update;

  if not found then
    raise exception 'NO_OPEN_SHIFT';
  end if;

  if p_closing_cash is null or p_closing_cash < 0 then
    raise exception 'INVALID_CLOSING_CASH';
  end if;

  select coalesce(sum(pp.amount),0)
  into v_cash_sales
  from public.pos_payments pp
  join public.pos_sales ps on ps.id = pp.sale_id
  where ps.shift_id = v_shift.id
    and ps.status in ('completed','refunded')
    and pp.method = 'cash';

  select coalesce(sum(pr.amount),0)
  into v_cash_refunds
  from public.pos_refunds pr
  where pr.shift_id = v_shift.id
    and pr.method = 'cash';

  select coalesce(sum(pcm.amount),0)
  into v_cash_in
  from public.pos_cash_movements pcm
  where pcm.shift_id = v_shift.id
    and pcm.movement_type = 'cash_in';

  select coalesce(sum(pcm.amount),0)
  into v_cash_out
  from public.pos_cash_movements pcm
  where pcm.shift_id = v_shift.id
    and pcm.movement_type = 'cash_out';

  v_cash_sales := round(v_cash_sales,2);
  v_cash_refunds := round(v_cash_refunds,2);
  v_cash_in := round(v_cash_in,2);
  v_cash_out := round(v_cash_out,2);

  v_expected := round(
    v_shift.opening_cash + v_cash_sales + v_cash_in - v_cash_out - v_cash_refunds,
    2
  );

  v_difference := round(p_closing_cash - v_expected,2);

  update public.pos_shifts s
  set
    status = 'closed',
    closing_cash = round(p_closing_cash,2),
    expected_cash = v_expected,
    difference = v_difference,
    notes = nullif(btrim(coalesce(p_notes,'')),''),
    closed_at = now()
  where s.id = v_shift.id;

  insert into public.pos_access_log(
    employee_id,
    terminal_id,
    event_type,
    success,
    details
  )
  values(
    v_employee.id,
    v_terminal.id,
    'shift_closed',
    true,
    jsonb_build_object(
      'shift_id', v_shift.id,
      'opening_cash', v_shift.opening_cash,
      'cash_sales', v_cash_sales,
      'cash_refunds', v_cash_refunds,
      'cash_in', v_cash_in,
      'cash_out', v_cash_out,
      'expected_cash', v_expected,
      'closing_cash', round(p_closing_cash,2),
      'difference', v_difference
    )
  );

  return jsonb_build_object(
    'ok', true,
    'shift_id', v_shift.id,
    'opening_cash', v_shift.opening_cash,
    'cash_sales', v_cash_sales,
    'cash_refunds', v_cash_refunds,
    'cash_in', v_cash_in,
    'cash_out', v_cash_out,
    'expected_cash', v_expected,
    'closing_cash', round(p_closing_cash,2),
    'difference', v_difference
  );
end;
$function$
;
CREATE OR REPLACE FUNCTION public.pos_create_sale(p_device_token text, p_items jsonb, p_payments jsonb, p_discount_amount numeric DEFAULT 0, p_notes text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_employee public.pos_employees%rowtype;
  v_terminal public.pos_terminals%rowtype;
  v_shift public.pos_shifts%rowtype;

  v_sale_id uuid;
  v_sale_number bigint;

  v_item jsonb;
  v_payment jsonb;
  v_product public.products%rowtype;

  v_product_id uuid;
  v_quantity integer;
  v_unit_price numeric(12,2);
  v_line_subtotal numeric(12,2);

  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2) := round(coalesce(p_discount_amount,0),2);
  v_total numeric(12,2) := 0;
  v_payment_total numeric(12,2) := 0;

  v_method text;
  v_amount numeric(12,2);
  v_reference text;

  v_max_discount numeric(12,2);
  v_item_count integer := 0;
begin
  -- Empleado autenticado.
  select e.*
  into v_employee
  from public.pos_employees e
  where e.auth_user_id = auth.uid();

  if not found then
    raise exception 'POS_EMPLOYEE_NOT_FOUND';
  end if;

  if v_employee.status <> 'active' then
    raise exception 'POS_EMPLOYEE_NOT_ACTIVE';
  end if;

  -- Terminal autorizada por token físico/local.
  select t.*
  into v_terminal
  from public.pos_terminals t
  where t.status = 'active'
    and t.device_token_hash =
      extensions.digest(convert_to(coalesce(p_device_token,''),'UTF8'),'sha256');

  if not found then
    raise exception 'TERMINAL_NOT_AUTHORIZED';
  end if;

  -- El cajero debe tener un turno abierto EN ESA terminal.
  select s.*
  into v_shift
  from public.pos_shifts s
  where s.employee_id = v_employee.id
    and s.terminal_id = v_terminal.id
    and s.status = 'open'
  order by s.opened_at desc
  limit 1
  for update;

  if not found then
    raise exception 'NO_OPEN_SHIFT';
  end if;

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'SALE_ITEMS_REQUIRED';
  end if;

  if p_payments is null
     or jsonb_typeof(p_payments) <> 'array'
     or jsonb_array_length(p_payments) = 0 then
    raise exception 'PAYMENT_REQUIRED';
  end if;

  -- ------------------------------------------------------------------------
  -- Primera pasada: bloquea inventario y calcula subtotal con precio servidor.
  -- ------------------------------------------------------------------------
  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop
    begin
      v_product_id := nullif(v_item ->> 'product_id','')::uuid;
      v_quantity := (v_item ->> 'quantity')::integer;
    exception when others then
      raise exception 'INVALID_SALE_ITEM';
    end;

    if v_product_id is null or v_quantity is null or v_quantity <= 0 then
      raise exception 'INVALID_SALE_ITEM';
    end if;

    select p.*
    into v_product
    from public.products p
    where p.id = v_product_id
      and p.status = 'active'
    for update;

    if not found then
      raise exception 'PRODUCT_NOT_AVAILABLE:%', v_product_id;
    end if;

    if v_product.stock < v_quantity then
      raise exception
        'INSUFFICIENT_STOCK:%:AVAILABLE=%:REQUESTED=%',
        v_product.id,
        v_product.stock,
        v_quantity;
    end if;

    v_unit_price :=
      round(coalesce(v_product.sale_price, v_product.price, 0),2);

    if v_unit_price < 0 then
      raise exception 'INVALID_PRODUCT_PRICE:%', v_product.id;
    end if;

    v_line_subtotal := round(v_unit_price * v_quantity,2);
    v_subtotal := v_subtotal + v_line_subtotal;
    v_item_count := v_item_count + v_quantity;
  end loop;

  v_subtotal := round(v_subtotal,2);

  if v_discount < 0 then
    raise exception 'INVALID_DISCOUNT';
  end if;

  -- Política inicial de autorización de descuentos.
  if v_employee.role = 'cashier' then
    v_max_discount := 0;
  elsif v_employee.role = 'supervisor' then
    v_max_discount := round(v_subtotal * 0.10,2);
  elsif v_employee.role = 'pos_admin' then
    v_max_discount := round(v_subtotal * 0.25,2);
  else
    raise exception 'INVALID_POS_ROLE';
  end if;

  if v_discount > v_max_discount then
    raise exception
      'DISCOUNT_NOT_AUTHORIZED:MAX=%',
      v_max_discount;
  end if;

  if v_discount > v_subtotal then
    raise exception 'DISCOUNT_EXCEEDS_SUBTOTAL';
  end if;

  v_total := round(v_subtotal - v_discount,2);

  -- ------------------------------------------------------------------------
  -- Pagos: validar total exacto.
  -- V1 permite pagos mixtos si la suma coincide exactamente.
  -- ------------------------------------------------------------------------
  for v_payment in
    select value
    from jsonb_array_elements(p_payments)
  loop
    v_method := lower(btrim(coalesce(v_payment ->> 'method','')));
    v_reference := nullif(btrim(coalesce(v_payment ->> 'reference','')),'');

    begin
      v_amount := round((v_payment ->> 'amount')::numeric,2);
    exception when others then
      raise exception 'INVALID_PAYMENT_AMOUNT';
    end;

    if v_method not in ('cash','card_terminal','transfer','other') then
      raise exception 'INVALID_PAYMENT_METHOD:%', v_method;
    end if;

    if v_amount is null or v_amount <= 0 then
      raise exception 'INVALID_PAYMENT_AMOUNT';
    end if;

    v_payment_total := v_payment_total + v_amount;
  end loop;

  v_payment_total := round(v_payment_total,2);

  if v_payment_total <> v_total then
    raise exception
      'PAYMENT_TOTAL_MISMATCH:EXPECTED=%:RECEIVED=%',
      v_total,
      v_payment_total;
  end if;

  -- ------------------------------------------------------------------------
  -- Cabecera.
  -- ------------------------------------------------------------------------
  insert into public.pos_sales(
    shift_id,
    employee_id,
    terminal_id,
    channel,
    status,
    currency,
    subtotal,
    discount_amount,
    total,
    notes,
    metadata
  )
  values(
    v_shift.id,
    v_employee.id,
    v_terminal.id,
    'pos',
    'completed',
    'MXN',
    v_subtotal,
    v_discount,
    v_total,
    nullif(btrim(coalesce(p_notes,'')),''),
    jsonb_build_object(
      'employee_number', v_employee.employee_number,
      'employee_role', v_employee.role,
      'terminal_name', v_terminal.name,
      'item_count', v_item_count
    )
  )
  returning id, sale_number
  into v_sale_id, v_sale_number;

  -- ------------------------------------------------------------------------
  -- Segunda pasada: snapshots + descuento de stock.
  -- Se vuelven a tomar los productos bloqueados en esta misma transacción.
  -- El descuento global se conserva en cabecera; V1 no distribuye descuento
  -- entre líneas para evitar errores de redondeo contable.
  -- ------------------------------------------------------------------------
  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop
    v_product_id := (v_item ->> 'product_id')::uuid;
    v_quantity := (v_item ->> 'quantity')::integer;

    select p.*
    into v_product
    from public.products p
    where p.id = v_product_id
    for update;

    v_unit_price :=
      round(coalesce(v_product.sale_price, v_product.price, 0),2);

    v_line_subtotal := round(v_unit_price * v_quantity,2);

    insert into public.pos_sale_items(
      sale_id,
      product_id,
      sku,
      product_name,
      unit_price,
      quantity,
      line_subtotal,
      discount_amount,
      line_total,
      product_snapshot
    )
    values(
      v_sale_id,
      v_product.id,
      v_product.sku,
      v_product.name,
      v_unit_price,
      v_quantity,
      v_line_subtotal,
      0,
      v_line_subtotal,
      jsonb_build_object(
        'name', v_product.name,
        'sku', v_product.sku,
        'brand', v_product.brand,
        'model', v_product.model,
        'condition', v_product.item_condition,
        'cover_image_url', v_product.cover_image_url,
        'currency', coalesce(v_product.currency,'MXN'),
        'catalog_price', v_product.price,
        'catalog_sale_price', v_product.sale_price,
        'pos_unit_price', v_unit_price
      )
    );

    insert into public.inventory_movements(
      product_id,
      order_id,
      pos_sale_id,
      movement_type,
      quantity_change,
      stock_before,
      stock_after,
      note
    )
    values(
      v_product.id,
      null,
      v_sale_id,
      'sale',
      -v_quantity,
      v_product.stock,
      v_product.stock - v_quantity,
      format('Venta POS #%s · %s', v_sale_number, v_terminal.name)
    );

    update public.products p
    set
      stock = p.stock - v_quantity,
      updated_at = now()
    where p.id = v_product.id;

    insert into public.pos_sale_events(
      sale_id,
      employee_id,
      terminal_id,
      event_type,
      details
    )
    values(
      v_sale_id,
      v_employee.id,
      v_terminal.id,
      'inventory_deducted',
      jsonb_build_object(
        'product_id', v_product.id,
        'sku', v_product.sku,
        'quantity', v_quantity,
        'stock_before', v_product.stock,
        'stock_after', v_product.stock - v_quantity
      )
    );
  end loop;

  -- Pagos.
  for v_payment in
    select value
    from jsonb_array_elements(p_payments)
  loop
    v_method := lower(btrim(v_payment ->> 'method'));
    v_amount := round((v_payment ->> 'amount')::numeric,2);
    v_reference := nullif(btrim(coalesce(v_payment ->> 'reference','')),'');

    insert into public.pos_payments(
      sale_id,
      method,
      amount,
      reference,
      metadata
    )
    values(
      v_sale_id,
      v_method,
      v_amount,
      v_reference,
      coalesce(v_payment -> 'metadata','{}'::jsonb)
    );

    insert into public.pos_sale_events(
      sale_id,
      employee_id,
      terminal_id,
      event_type,
      details
    )
    values(
      v_sale_id,
      v_employee.id,
      v_terminal.id,
      'payment_recorded',
      jsonb_build_object(
        'method', v_method,
        'amount', v_amount,
        'reference', v_reference
      )
    );
  end loop;

  insert into public.pos_sale_events(
    sale_id,
    employee_id,
    terminal_id,
    event_type,
    details
  )
  values(
    v_sale_id,
    v_employee.id,
    v_terminal.id,
    'sale_completed',
    jsonb_build_object(
      'sale_number', v_sale_number,
      'subtotal', v_subtotal,
      'discount_amount', v_discount,
      'total', v_total,
      'payment_total', v_payment_total
    )
  );

  return jsonb_build_object(
    'ok', true,
    'sale_id', v_sale_id,
    'sale_number', v_sale_number,
    'currency', 'MXN',
    'subtotal', v_subtotal,
    'discount_amount', v_discount,
    'total', v_total,
    'item_count', v_item_count
  );
end;
